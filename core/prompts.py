def build_messages(request, history, chunks, secret=''):
    """Контекст сериализуется как данные; история не может назначить роль system."""
    content = {
        'history': history,
        'current_message': request.message,
        'documents': [{'chunk_id': f'D{i}', 'title': c.title, 'section': c.section,
                       'text': c.text} for i, c in enumerate(chunks, 1)],
    }
    data = json.dumps(content, ensure_ascii=False)
    # Даже случайно вставленный в документ или сообщение действующий ключ не передаём модели.
    if secret:
        data = data.replace(secret, '[секрет удалён]')
    instruction = SYSTEM_PROMPT
    if (chunks and load_profile_question(request.message)
            and re.search(r'выработк\w*\s+не\s+совпад', chunks[0].text, re.I)):
        # Фокус следует из запроса и найденного ограничения. Иначе общая
        # консультация уводит к площади кровли, не проверив совпадение профилей.
        instruction += (
            '\nВ текущем вопросе сначала объясни ограничение совпадения дневной выработки '
            'с нагрузкой. При основном потреблении вечером экономическую выгоду нельзя '
            'подтвердить без данных о дневном потреблении. Раздели экономию и резерв. '
            'Для следующего шага уточни потребление днём и вечером.')
    return [{'role': 'system', 'content': instruction}, {'role': 'user', 'content': data}]


