def build_messages(request, history, chunks, secret='', *, state=None):
    """Контекст сериализуется как данные; история не может назначить роль system."""
    state = state if state is not None else build_consultation_state(request)
    intent = state.intent
    content = {
        'history': history,
        'current_message': request.message,
        'documents': [{'chunk_id': f'D{i}', 'title': c.title, 'section': c.section,
                       'text': c.text} for i, c in enumerate(chunks, 1)],
    }
    # Выделяем только дословные пользовательские поправки из уже ограниченной
    # истории. Это подсказка внимания, не синтез фактов и не возврат отброшенной
    # истории. Целые сообщения и общий лимит не позволяют раздуть контекст.
    correction = re.compile(r'исправля\w*|поправ\w*|уточняю|ошибся|ошиблась|'
                            r'вс[её][ -]таки|свеж\w*\s+выгруз', re.I)
    corrections, correction_chars = [], 0
    for turn in reversed(history + [{'role': 'user', 'content': request.message}]):
        if turn['role'] == 'user' and correction.search(turn['content']):
            if len(corrections) >= 2:
                break
            if correction_chars + len(turn['content']) > 600:
                continue
            corrections.append(turn['content'])
            correction_chars += len(turn['content'])
    if corrections:
        content['client_corrections'] = list(reversed(corrections))
    if state.facts:
        # Небольшая подсказка использует тот же отбор, что и запасной черновик.
        # История остаётся основанием для единиц и сложных связей; ограничение
        # целыми выдержками не раздувает контекст и не обрезает число посередине.
        facts = [fact.quote for fact in state.facts]
        excerpts, size = [], 0
        for fact in reversed(facts):
            if len(excerpts) < 6 and size + len(fact) <= 600:
                excerpts.append(fact)
                size += len(fact)
        if excerpts:
            content['client_fact_excerpts'] = list(reversed(excerpts))
    if state.preparation_requested or state.sufficiency_requested:
        # Обязательность списка не должна теряться между поиском и моделью:
        # одно место в начале контекста не мешало выбирать общую справку вместо него.
        # Соседний список другого продукта не становится обязательным лишь
        # потому, что поиск включил его в общий контекст.
        headings = {PREPARATION_SECTIONS[topic] for topic in intent.active
                    if topic in PREPARATION_SECTIONS}
        content['required_checklists'] = [f'D{i}' for i, chunk in enumerate(chunks, 1)
                                         if (chunk.section or '').lower() in headings]
    # Это план полноты, а не новые факты о клиенте. Тот же план получит
    # редактор: список из соседнего документа не должен менять задачу ответа.
    content['answer_plan'] = {
        'topics_from_user': list(intent.active),
        'summary_requested': state.summary_requested,
        'preparation_requested': state.preparation_requested,
        'sufficiency_requested': state.sufficiency_requested,
        'focus': list(state.focus),
        'extracted_parameter_kinds': sorted({fact.kind for fact in state.facts if fact.kind}),
        'preparation_source_ids': content.get('required_checklists', []),
    }
    # Проверяем значения до сериализации: кавычки и обратные слеши в ключе
    # экранируются JSON и не совпадают с поиском по готовой JSON-строке.
    data = json.dumps(redact_secret(content, secret), ensure_ascii=False)
    instruction = SYSTEM_PROMPT
    if corrections:
        instruction += ('\nВ client_corrections отдельно выделены дословные поправки пользователя. '
                        'Сверь с ними известные параметры; старое значение не возвращается '
                        'из прежних реплик. Эта подсказка не заменяет остальную историю.')
    if content.get('client_fact_excerpts'):
        instruction += ('\nclient_fact_excerpts — неполная выборка актуальных дословных сведений '
                        'для учёта известных сведений и резюме. Единицы и связи '
                        'проверь по history. Цель и выбранный продукт не выводи из документов '
                        'или своих прошлых ответов; неизвестное так и обозначь.')
    if not intent.active:
        # Найденный документ не доказывает, что клиент использует именно этот
        # продукт. Особенно опасно безусловное «да» о неизвестной системе клиента.
        instruction += (
            '\nПродукт клиента не определён. Общую справку дай по источникам; '
            'свойство конкретного продукта опиши условно, не приписывая его '
            'системе клиента. Для индивидуальной цены уточни предмет вместо '
            'случайного прайса. Неопределённость темы не требует полного отказа '
            'от подтверждённой части ответа.')
    if state.preparation_requested:
        instruction += (
            '\nТекущий запрос — перечень данных или первый шаг. Дай конкретный список '
            'для выбранного продукта, отделив уже известное. Ответь также на остальные '
            'прямые вопросы этой реплики. Один следующий вопрос допустим, если '
            'помогает начать работу и не повторяет список; не собирай параметры '
            'другого продукта.')
    if content.get('required_checklists'):
        instruction += (
            '\nВ required_checklists указаны ID списков подготовки выбранных продуктов. '
            'Сверь каждый параметр, включая части составных пунктов: известное '
            'отметь, неизвестное перечисли. Количество приборов не подтверждает '
            'тип. Общая справка не заменяет продуктовый список; при проверке '
            'достаточности явно укажи недостающие условия.')
    if 'солнечные электростанции' in intent.active and 'load_profile' in state.focus:
        # Фокус следует из запроса и найденного ограничения. Иначе общая
        # консультация уводит к площади кровли, не проверив совпадение профилей.
        instruction += (
            '\nВ текущем вопросе сначала объясни ограничение совпадения дневной выработки '
            'с нагрузкой. При основном потреблении вечером экономическую выгоду нельзя '
            'подтвердить без данных о дневном потреблении. Раздели экономию и резерв. '
            'Для следующего шага уточни потребление днём и вечером.')
    if 'солнечные электростанции' in intent.active and 'reserve' in state.focus:
        instruction += (
            '\nВопрос связан с резервированием. По documents объясни подходящую '
            'конфигурацию, существенные изменения компонентов и условия обеспечения '
            'нагрузки и зарядки. Для подбора уточни неизвестные критичную нагрузку '
            'и длительность автономии. Они не заменяются присоединённой мощностью, '
            'ценовой категорией или уровнем напряжения.')
    return [{'role': 'system', 'content': instruction}, {'role': 'user', 'content': data}]


def build_review_messages(messages, draft, secret=''):
    """Вторая проверка использует те же документы и историю, без эталонных ответов."""
    payload = json.loads(messages[1]['content'])
    # Модель могла добавить непрошеный черновик, отброшенный assemble.
    # Очищаем также эти исходные поля перед передачей редактору.
    payload['draft'] = redact_secret(draft, secret)
    # Общие правила уже находятся в messages[0]. Повторение их полным списком
    # переполняло контекст review при валидном исходном запросе (8192 токена).
    # Здесь остаются только задача редактора и формат проверочного результата.
    instruction = (
        'Отредактируй draft по всем исходным правилам выше. Проверь по documents '
        'вывод, единицы, условия и границы ответственности; по user-истории — '
        'актуальные факты, цель, выбранный продукт и последнюю поправку. '
        'Не превращай числовой порог в полученное разрешение. Не переноси '
        'условия, бесплатность и подготовительные данные между продуктами. '
        'Ответь на все части вопроса. При смене конфигурации сохрани необходимые '
        'компоненты и условия расчёта из источника, включая нагрузку и зарядку. '
        'Убирай соседнюю справку, но не ограничения, без которых вывод неверен. '
        'При неопределённой услуге не назначай её клиенту по найденному документу. '
        'В резюме не включай поручения о форме ответа и не возвращай старые значения. '
        'Сверь result с answer_plan: выполни все запрошенные задачи; '
        'не превращай справку в подготовку проекта. Проверь отдельно прямой ответ, '
        'существенные условия, факты клиента и следующий шаг, не подменяя один другим. '
        'Для следующего шага выбери действительно недостающий параметр текущей задачи: '
        'резерв требует нагрузки и длительности, экономика — профиля потребления. '
        'Известное повторно не спрашивай; к чистой справке вопрос не обязателен. '
        'Устрани повтор вопроса, сохрани полезный конкретный шаг. '
        'Каждое изменение содержания или вопроса обоснуй в issues. '
        'Верни JSON: issues — до трёх конкретных замечаний по 240 символов '
        '(или []); follow_up_question — этот вопрос либо null; result — '
        'окончательный объект по исходной схеме. При issues=[] верни result=draft '
        'и follow_up_question=null. При исправлении в result.answer оставь вывод '
        'и условия, следующий вопрос вынеси отдельно. Перепроверь evidence относительно '
        'итогового текста: от одного до трёх исходных ID для answered.'
    )
    if payload.get('required_checklists'):
        instruction += (
            ' Прежде чем принять result, сверь каждый пункт required_checklists '
            'с ответом. Восстанови пропущенные пункты, отдели уже известные от '
            'недостающих. Количество и тип приборов — разные параметры; если известно '
            'только количество, тип остаётся недостающим. '
            'Не заменяй продуктовые списки общими данными об объекте.')
    return [dict(messages[0], content=messages[0]['content'] + '\n' + instruction),
            {'role': 'user', 'content': json.dumps(payload, ensure_ascii=False)}]
