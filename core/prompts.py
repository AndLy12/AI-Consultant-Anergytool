def build_messages(request, history, chunks, secret=''):
    """Контекст сериализуется как данные; история не может назначить роль system."""
    content = {
        'history': history,
        'current_message': request.message,
        'documents': [{'chunk_id': f'D{i}', 'title': c.title, 'section': c.section,
                       'text': c.text} for i, c in enumerate(chunks, 1)],
    }
    if data_checklist_question(request.message) or data_sufficiency_question(request.message):
        # Обязательность списка не должна теряться между поиском и моделью:
        # одно место в начале контекста не мешало выбирать общую справку вместо него.
        content['required_checklists'] = [f'D{i}' for i, chunk in enumerate(chunks, 1)
                                           if (chunk.section or '').lower() in PREPARATION_SECTIONS.values()]
    data = json.dumps(content, ensure_ascii=False)
    # Даже случайно вставленный в документ или сообщение действующий ключ не передаём модели.
    if secret:
        data = data.replace(secret, '[секрет удалён]')
    instruction = SYSTEM_PROMPT
    if data_checklist_question(request.message):
        instruction += (
            '\nТекущий запрос — перечень данных или первый шаг. Дай конкретный список '
            'для выбранного продукта, отделив уже известное. Не добавляй следующий '
            'вопрос после списка и не собирай параметры другого продукта.')
    if content.get('required_checklists'):
        instruction += (
            '\nВ required_checklists указаны ID списков подготовки выбранных продуктов. '
            'Учти каждый пункт этих списков: известное отметь как уже сообщённое, '
            'остальное перечисли как недостающие данные. Общая справка о регионе, '
            'мощности или потреблении не заменяет продуктовый список. '
            'При проверке достаточности явно назови неизвестные обязательные условия.')
    if (chunks and load_profile_question(request.message)
            and re.search(r'выработк\w*\s+не\s+совпад', chunks[0].text, re.I)):
        # Фокус следует из запроса и найденного ограничения. Иначе общая
        # консультация уводит к площади кровли, не проверив совпадение профилей.
        instruction += (
            '\nВ текущем вопросе сначала объясни ограничение совпадения дневной выработки '
            'с нагрузкой. При основном потреблении вечером экономическую выгоду нельзя '
            'подтвердить без данных о дневном потреблении. Раздели экономию и резерв. '
            'Для следующего шага уточни потребление днём и вечером.')
    return [{'role': 'system', 'content': instruction}, {'role': 'user', 'content': data}]


def build_review_messages(messages, draft):
    """Вторая проверка использует те же документы и историю, без эталонных ответов."""
    payload = json.loads(messages[1]['content'])
    payload['draft'] = draft
    instruction = (
        'Проверь draft и верни окончательный JSON по прежней схеме. '
        'Сначала проверь, ответил ли draft на последнюю реплику и выполнил ли все условия. '
        'Удали неподтверждённые и не относящиеся к вопросу сведения. '
        'Причины, способы передачи энергии и правила продажи тоже требуют основания в документах. '
        'Не спрашивай о том, что клиент уже сообщил, включая поверхность размещения и цель. '
        'В выводе и резюме используй последнюю поправку клиента по каждому параметру; '
        'не переноси предположение ассистента в факты клиента. '
        'В резюме не выводи тип организации или характеристики объекта из названия компании. '
        'Общий положительный вывод допустим, только если выполнены все обязательные условия. '
        'Если часть условий неизвестна, объясни, что подходит и что ещё надо проверить. '
        'В вопросе о составе данных перечисли конкретные недостающие параметры. '
        'При расхождении источников сохрани оговорку, не давай категоричную гарантию. '
        'Для разных групп приборов сохрани подходящий способ работы с каждой. '
        'Бесплатным называй только прямо описанный бесплатный этап. '
        'Проверь, что свойства выработки, потребления и экономического эффекта не смешаны. '
        'Не выдавай диапазон мощности станции за допустимый диапазон нагрузки клиента. '
        'Не объявляй перечень достаточным для запуска, если это не следует из источника. '
        'Добавь пропущенное существенное условие, если оно подтверждено документом. '
        'В follow_up_question верни вопрос только тогда, когда неизвестный параметр '
        'меняет ответ или запрошенный расчёт. Для общего свойства, достаточного ответа '
        'и списка данных верни null. Упоминание своего объекта само по себе не повод спрашивать. '
        'Когда спрашиваешь пороговый параметр, объясни применимый порог из документа. '
        'При вопросе о составе данных убери ценовую справку и назови нужные сведения. '
        'Не добавляй неподтверждённых обещаний и цифр. '
        'Проверь каждое существенное утверждение отдельно: число с единицей, область '
        'применимости, гарантию, срок и бесплатность. Источник о бесплатном расчёте '
        'не доказывает ни бесплатность обследования, ни оплату монтажа после проекта. '
        'Удали только неподтверждённую часть, сохрани полезный ответ с точным ограничением. '
        'Сохрани правильные факты и одно полезное уточнение, если оно нужно. '
        'Перед финальным ответом составь issues: найди неверные выводы, '
        'недоказанные обещания, пропущенные условия и ненужные уточнения. '
        'Для бесплатного этапа укажи в issues, если прилагательное перенесено '
        'с расчёта на обследование: это разные работы. '
        'Для проверки достаточности данных найди каждое обязательное условие. '
        'Сопоставь каждое с явными данными клиента, не с предположением ассистента. '
        'При неизвестном условии замени безусловное «данных достаточно» условным выводом. '
        'Слова «суточные показания» сами по себе не подтверждают разбивку день/ночь. '
        'Перепроверь evidence относительно итогового текста. '
        'В этом проверочном вызове верни JSON с тремя полями: '
        'issues — до трёх замечаний по 240 символов максимум (пустой список при их отсутствии), '
        'follow_up_question — необходимый для текущего решения вопрос; иначе null, '
        'включая справку о функции и уже известные сведения. '
        'result — исправленный объект ответа по прежней схеме. '
        'В result.answer дай вывод и существенные условия, а следующий вопрос вынеси '
        'в follow_up_question: приложение соединит их. '
        'Пример: {"issues":["Убрано неподтверждённое обещание"],'
        '"follow_up_question":null,"result":{"status":"answered","answer":"Исправленный ответ","evidence":["D1"]}}.'
    )
    if payload.get('required_checklists'):
        instruction += (
            ' Прежде чем принять result, сверь каждый пункт required_checklists '
            'с ответом. Восстанови пропущенные пункты, отдели уже известные от '
            'недостающих. Не заменяй продуктовые списки общими данными об объекте.')
    return [dict(messages[0], content=messages[0]['content'] + '\n' + instruction),
            {'role': 'user', 'content': json.dumps(payload, ensure_ascii=False)}]
