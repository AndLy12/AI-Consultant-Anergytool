/**
 * Приветствие на пустом чате по времени суток (макет Figma 9:2: «Добрый вечер!»).
 *
 * Берём время устройства пользователя, а не московское: «доброе утро» должно
 * совпадать с тем, что видит человек у себя. Имени в приветствии нет — backend
 * не хранит имя пользователя (решение владельца от 2026-11-16).
 */

/** Границы частей суток (час включительно): утро 5–11, день 12–16, вечер 17–22, ночь 23–4. */
export function greetingFor(date: Date): string {
  const hour = date.getHours()
  if (hour >= 5 && hour < 12) return 'Доброе утро!'
  if (hour >= 12 && hour < 17) return 'Добрый день!'
  if (hour >= 17 && hour < 23) return 'Добрый вечер!'
  return 'Доброй ночи!'
}
